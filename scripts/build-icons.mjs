// Reads every icon Sakuga Version 221 draws (the design's bundle.js: SVG_ICONS, PICKER_ICONS, OCCASION_ICONS, PATHS) and writes
//   src/icons/icons.svg  one <symbol> per icon, the file the browser fetches once and caches, and
//   src/ui/Icon/names.ts the IconName union, so a name that has no symbol fails the type check, and iconNames, the list.
// A symbol carries its own fill and stroke, so <use> draws it exactly as the bundle did; colour comes from currentColor.
// The stroke width of a path icon reads --icon-stroke-width, which Icon's strokeWidth prop sets.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, brotliCompressSync } from 'node:zlib';
import { hasDesign } from './design.mjs';
if (!hasDesign()) { console.log('Icons: the reference files are not available, so src/icons/icons.svg is used as it is.'); process.exit(0); }
const { readIconSource } = await import('./icon-source.mjs');
import { optimizeIconSprite } from './optimize-icons.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { symbols, names, listed } = readIconSource();
const sprite = optimizeIconSprite(symbols);
/* A drawn icon far from square (a standing figure) gets its shape as an aspect-ratio. The bundle's inline svg has it from its
   viewBox; drawn through <use>, a percentage-sized icon (a placeholder silhouette) would take a box of another width, and the
   centred drawing land a fraction of a pixel away. A fixed size sets both sides, so the ratio changes nothing there. */
const tall = (vb) => { const [, , w, h] = vb.split(' ').map(Number); return h > w * 1.25 || w > h * 1.25; };
const shapes = [...sprite.matchAll(/<symbol id="([^"]+)" viewBox="([^"]+)"/g)].filter((m) => tall(m[2]));
writeFileSync(join(root, 'src/icons/icons.svg'), sprite);
writeFileSync(join(root, 'src/ui/Icon/names.ts'),
  '// Generated by scripts/build-icons.mjs from the icons in src/icons/icons.svg. Do not edit.\n' +
  'export type IconName =\n' + names.map((n) => `  | '${n}'`).join('\n') + ';\n\n' +
  '/** Every icon, in the order Version 221 lists them (Sakuga.iconNames): the path icons, then the drawn ones. */\n' +
  'export const iconNames: readonly IconName[] = [\n' + listed.map((n) => `  '${n}',`).join('\n') + '\n];\n\n' +
  '/** The drawn icons far from square (standing figures), by their shape as a CSS aspect-ratio. */\n' +
  'export const iconRatios: Partial<Record<IconName, string>> = {\n' + shapes.map((m) => { const [, , w, h] = m[2].split(' '); return `  '${m[1]}': '${w} / ${h}',`; }).join('\n') + '\n};\n');
console.log(`${names.length} icons: ${Buffer.byteLength(sprite)} bytes, gzip ${gzipSync(sprite, { level: 9 }).length}, Brotli ${brotliCompressSync(sprite).length}`);
